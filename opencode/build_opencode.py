#!/usr/bin/env python3
"""Render an OpenCode-native hyperresearch skill from a hyperresearch install.

Source of truth is the output of `hyperresearch install --target all` in a
hyperresearch repository/install:

    <repo>/.claude/skills/hyperresearch*/SKILL.md   (entry + 18 step procedures)
    <repo>/.claude/agents/hyperresearch-*.md        (16 subagents)

The rendered files are native OpenCode definitions:

    <global-dir>/skills/hyperresearch/SKILL.md
    <global-dir>/skills/hyperresearch-*/SKILL.md
    <global-dir>/agents/hyperresearch-*.md
    <global-dir>/commands/hyperresearch.md
    <global-dir>/opencode.json(c)                  (merged, existing keys preserved)

With --scope project the output goes to <project>/.opencode/ plus opencode.jsonc
and an AGENTS.md section instead.

Usage:
    python build_opencode.py --scope global --repo F:/hyperresearch-skill
    python build_opencode.py --scope project --repo F:/hyperresearch-skill --project .

The --repo option can also be supplied through the HYPERRESEARCH_REPO environment
variable. Re-run after `hyperresearch install`, `hyperresearch profile use`, or
any change to the generated Claude templates.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

GENERATED_COMMENT = (
    "<!-- generated by hyperresearch-opencode -- do not edit by hand; "
    "edit the upstream profile/template and re-run the adapter -->"
)

CLI_SUBCOMMANDS = (
    "init|install|archive-run|vault-tag|run|levers|profile|fetch|fetch-batch|"
    "scholar|note|search|lint|sync|escalation|sources|graph|claims|index|topic|"
    "dedup|link|batch|embed|export|import|git|watch|serve|mcp|setup|extract|"
    "page|file|codex|anchor|outline|check|verify"
)
CLI_RE = re.compile(rf"(?<![\w./\\:-])hyperresearch(?=\s+(?:{CLI_SUBCOMMANDS})\b)")
ABS_CLI_RE = re.compile(r"[^\s`\"']*?/hyperresearch(?:\.exe)?(?=\s|$)")


@dataclass(frozen=True)
class Layout:
    repo: Path          # hyperresearch install: templates, venv, CLI
    adapter: Path       # this repository: helper scripts and instructions template
    global_root: Path   # ~/.config/opencode by default
    project: Path       # project directory for --scope project
    cli: Path           # resolved hyperresearch CLI
    python: Path        # resolved python interpreter for the helper scripts

    @property
    def claude_skills(self) -> Path:
        return self.repo / ".claude" / "skills"

    @property
    def claude_agents(self) -> Path:
        return self.repo / ".claude" / "agents"

    @property
    def local_root(self) -> Path:
        return self.project / ".opencode"

    @property
    def venv_bin(self) -> Path:
        return self.repo / ".venv" / ("Scripts" if sys.platform == "win32" else "bin")

    @property
    def adapter_script(self) -> Path:
        return self.adapter / "build_opencode.py"

    @property
    def gate_script(self) -> Path:
        return self.adapter / "artifact_gate.py"

    @property
    def skip_log_script(self) -> Path:
        return self.adapter / "patch_skip_log.py"

    @property
    def instructions_file(self) -> Path:
        return self.adapter / "OPENCODE_INSTRUCTIONS.md"

    @staticmethod
    def string(path: Path) -> str:
        return path.as_posix()


