def merge_global_config(layout: Layout) -> Path:
    layout.global_root.mkdir(parents=True, exist_ok=True)
    jsonc = layout.global_root / "opencode.jsonc"
    config = jsonc if jsonc.exists() else layout.global_root / "opencode.json"
    if config.exists():
        try:
            data = json.loads(config.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise RuntimeError(f"cannot parse {config}: {exc}. Merge the adapter settings manually.") from exc
        if not isinstance(data, dict):
            raise RuntimeError(f"{config} is not a JSON object")
    else:
        data = {}

    data.setdefault("$schema", "https://opencode.ai/config.json")
    experimental = data.setdefault("experimental", {})
    if not isinstance(experimental, dict):
        raise RuntimeError(f"experimental in {config} is not an object")
    experimental["todo"] = True

    rules = data.get("permissions", [])
    if not isinstance(rules, list):
        raise RuntimeError(f"permissions in {config} is not an array")
    rules = [
        r for r in rules
        if not (isinstance(r, dict) and str(r.get("resource", "")).startswith("hyperresearch"))
    ]
    rules += [
        {"action": "skill", "resource": "hyperresearch*", "effect": "allow"},
        {"action": "subagent", "resource": "hyperresearch-*", "effect": "allow"},
    ]
    data["permissions"] = rules

    instructions = data.get("instructions", [])
    if not isinstance(instructions, list):
        raise RuntimeError(f"instructions in {config} is not an array")
    instruction_path = Layout.string(layout.instructions_file)
    instructions = [
        item for item in instructions
        if not (isinstance(item, str) and item.endswith("OPENCODE_INSTRUCTIONS.md"))
    ]
    instructions.append(instruction_path)
    data["instructions"] = instructions

    config.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return config


