def detect_repo() -> Path | None:
    env = os.getenv("HYPERRESEARCH_REPO")
    if env:
        return Path(env).expanduser().resolve()
    script_dir = Path(__file__).resolve().parent
    for candidate in (script_dir, script_dir.parent):
        if (candidate / ".claude" / "skills").is_dir():
            return candidate
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", type=Path, default=None, help="hyperresearch install with .claude/skills and .venv (or set HYPERRESEARCH_REPO)")
    parser.add_argument("--scope", choices=("global", "project"), default="global", help="global (default): ~/.config/opencode; project: <project>/.opencode")
    parser.add_argument("--project", type=Path, default=Path.cwd(), help="project directory for --scope project (default: cwd)")
    parser.add_argument("--global-dir", type=Path, default=Path.home() / ".config" / "opencode", help="OpenCode global config directory")
    args = parser.parse_args()

    repo = (args.repo or detect_repo())
    if repo is None:
        print("error: no hyperresearch install found; pass --repo <path> or set HYPERRESEARCH_REPO", file=sys.stderr)
        return 2
    repo = repo.expanduser().resolve()
    venv_bin = repo / ".venv" / ("Scripts" if sys.platform == "win32" else "bin")
    cli = venv_bin / ("hyperresearch.exe" if sys.platform == "win32" else "hyperresearch")
    python = venv_bin / ("python.exe" if sys.platform == "win32" else "python")
    if not cli.is_file():
        on_path = shutil.which("hyperresearch")
        if on_path:
            cli = Path(on_path)
    if not python.is_file():
        python = Path(sys.executable)
    layout = Layout(
        repo=repo,
        adapter=Path(__file__).resolve().parent,
        global_root=args.global_dir.expanduser().resolve(),
        project=args.project.expanduser().resolve(),
        cli=cli,
        python=python,
    )

    if not layout.claude_skills.is_dir() or not layout.claude_agents.is_dir():
        print(f"error: {repo} has no .claude/skills and .claude/agents; run `hyperresearch install . --target all` there first", file=sys.stderr)
        return 1
    if shutil.which(str(cli)) is None:
        print(f"error: hyperresearch CLI not found at {cli} (and not on PATH)", file=sys.stderr)
        return 1

    skill_files = sorted(layout.claude_skills.glob("hyperresearch*/SKILL.md"))
    agent_files = sorted(layout.claude_agents.glob("hyperresearch-*.md"))
    if not skill_files or not agent_files:
        print("error: no generated hyperresearch skills/agents found", file=sys.stderr)
        return 1

    base = layout.global_root if args.scope == "global" else layout.local_root
    skills_root = base / "skills"
    agents_root = base / "agents"
    commands_root = base / "commands"
    for directory in (skills_root, agents_root, commands_root):
        directory.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []
    for src in skill_files:
        skill_id = src.parent.name
        dst = skills_root / skill_id / "SKILL.md"
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(translate_skill(src.read_text(encoding="utf-8"), skill_id, args.scope, layout), encoding="utf-8")
        written.append(dst)

    for src in agent_files:
        agent_id, content = render_agent(src, layout)
        dst = agents_root / f"{agent_id}.md"
        dst.write_text(content, encoding="utf-8")
        written.append(dst)

    cmd = commands_root / "hyperresearch.md"
    cmd.write_text(COMMAND, encoding="utf-8")
    written.append(cmd)

    if args.scope == "global":
        layout.instructions_file.write_text(global_instructions_text(layout), encoding="utf-8")
        written.append(layout.instructions_file)
        written.append(merge_global_config(layout))
    else:
        config = layout.project / "opencode.jsonc"
        if config.exists():
            print(f"note: {config} already exists — left untouched")
        else:
            config.write_text(OPENCODE_JSONC, encoding="utf-8")
            written.append(config)
        agents_md = layout.project / "AGENTS.md"
        existing = agents_md.read_text(encoding="utf-8") if agents_md.exists() else "# AGENTS\n"
        if "<!-- opencode-adapter:start -->" not in existing:
            agents_md.write_text(existing.rstrip() + "\n" + agents_section(layout), encoding="utf-8")
            written.append(agents_md)

    print(f"Rendered {len(written)} files for scope={args.scope} into {Layout.string(base)}")
    print(f"Source install: {Layout.string(repo)}")
    for path in written:
        print(f"  {path}")
    return 0


