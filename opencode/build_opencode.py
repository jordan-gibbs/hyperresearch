def translate_common(text: str, layout: Layout) -> str:
    text = re.sub(r"<!-- rendered from profile [^\n]*? -->", GENERATED_COMMENT, text, count=1)
    text = re.sub(r'Skill\(skill:\s*"([^"]+)"\)', r'skill(id: "\1")', text)
    text = text.replace("Skill tool", "skill tool")
    text = text.replace("Skill calls", "skill calls")
    text = text.replace("Skill invocation", "skill invocation")
    text = re.sub(r"\bSkill\b", "skill", text)
    text = re.sub(r"\bTask calls\b", "subagent calls", text)
    text = re.sub(r"\bTask call\b", "subagent call", text)
    text = re.sub(r"\bTask tool\b", "subagent tool", text)
    text = re.sub(r"\bTask prompt\b", "subagent prompt", text)
    text = text.replace("subagent_type:", "agent:")
    text = text.replace("TodoWrite", "todowrite")
    for old, new in (
        ("WebSearch", "websearch"),
        ("Read", "read"),
        ("Write", "write"),
        ("Edit", "edit"),
        ("Bash", "shell"),
    ):
        text = re.sub(rf"\b{old}\b", new, text)
    cli = Layout.string(layout.cli)
    text = ABS_CLI_RE.sub(cli, text)
    text = CLI_RE.sub(cli, text)
    text = text.replace(".claude/skills/", ".opencode/skills/")
    text = text.replace("```bash", "```shell")
    return text


